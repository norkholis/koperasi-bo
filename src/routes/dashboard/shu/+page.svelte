    // SHU operations
    async function generateSHUReport() {
        try {
            const response = await axios.post("/shu/generate", generateForm);

            generatedReport = response.data.data;

            showSuccessNotification("Laporan SHU berhasil digenerate!");
        } catch (error: any) {
            console.error("❌ Error generating SHU report:", error);
            showError(
                error.response?.data?.message || error.message,
                "Generate Failed",
            );
        }
    }

    async function generateAutoSHUReport() {
        try {
            const response = await axios.post(
                "/shu/generate-auto",
                autoGenerateForm,
            );

            autoGeneratedReport = response.data.data;

            showSuccessNotification(
                "Laporan SHU otomatis berhasil digenerate!",
            );
        } catch (error: any) {
            console.error("❌ Error generating automated SHU report:", error);
            showError(
                `Gagal generate laporan SHU otomatis: ${error.response?.data?.message || error.message}`,
            );
        }
    }

    async function saveAutoSHUReport() {
        if (!autoGeneratedReport) {
            showWarning("Silakan generate laporan otomatis terlebih dahulu");
            return;
        }

        try {
            // Convert values with extra validation
            const totalSHU = Math.round(
                Number(autoGeneratedReport.total_shu_koperasi) || 0,
            );
            const tahun =
                Number(autoGeneratedReport.tahun) || new Date().getFullYear();
            const pendapatanOp = Math.round(
                Number(autoGeneratedReport.pendapatan_operasional) || 0,
            );
            const pendapatanNonOp = Math.round(
                Number(autoGeneratedReport.pendapatan_non_operasional) || 0,
            );
            const bebanOp = Math.round(
                Number(autoGeneratedReport.beban_operasional) || 0,
            );
            const bebanNonOp = Math.round(
                Number(autoGeneratedReport.beban_non_operasional) || 0,
            );
            const bebanPajak = Math.round(
                Number(autoGeneratedReport.beban_pajak) || 0,
            );

            // Check if SHU Total is valid for saving
            if (totalSHU <= 0) {
                showError(
                    `Tidak dapat menyimpan laporan SHU karena total SHU adalah ${formatCurrency(totalSHU)}.\n\nPastikan pendapatan lebih besar dari total beban untuk menghasilkan SHU positif.`,
                );
                return;
            }

            // Use the EXACT structure from API documentation
            const saveData = {
                tahun: tahun,
                pendapatan_operasional: pendapatanOp,
                pendapatan_non_operasional: pendapatanNonOp,
                beban_operasional: bebanOp,
                beban_non_operasional: bebanNonOp,
                beban_pajak: bebanPajak,
                total_shu: totalSHU, // This is the correct field name from API docs
                status: "draft",
                shu_report: autoGeneratedReport, // Include the detailed member breakdown
            };

            const response = await axios.post("/shu/save-auto", saveData);

            // Refresh data
            await invalidateAll();
            closeModals();
            showSuccessNotification(
                "Laporan SHU otomatis berhasil disimpan ke daftar!",
            );
        } catch (error: any) {
            console.error("Save failed:", error);
            console.error("❌ Error status:", error.response?.status);

            const errorMessage =
                error.response?.data?.message ||
                error.response?.data?.error ||
                error.message ||
                "Unknown error occurred";

            showError(`Gagal menyimpan laporan SHU otomatis: ${errorMessage}`);
        }
    }

    async function generateUserSHU() {
        try {
            // User SHU generation now requires year input according to API docs
            const currentYear = new Date().getFullYear();
            const requestData = {
                Tahun: currentYear,
                TotalSHUKoperasi: 0, // Try with the fields the error mentioned
            };

            const response = await axios.post(
                `/shu/user/${currentUser.id}/generate`,
                requestData,
            );

            // Refresh user history
            await invalidateAll();
            closeModals();
            showSuccessNotification("SHU pribadi berhasil digenerate!");
        } catch (error: any) {
            console.error("❌ Error generating user SHU:", error);
            console.error("❌ Error response:", error.response?.data);
            console.error("❌ Error status:", error.response?.status);

            // Handle specific error cases
            if (error.response?.status === 403) {
                showError(
                    "Access Denied: Anda tidak memiliki izin untuk generate SHU pribadi.\n\nKemungkinan penyebab:\n• Fitur belum aktif untuk user biasa\n• Perlu izin khusus dari admin\n• Role/permission tidak sesuai",
                );
                return;
            }

            if (error.response?.status === 401) {
                showError(
                    "Authentication Error: Sesi login Anda mungkin telah berakhir.\n\nSilakan refresh halaman dan login kembali.",
                );
                return;
            }

            // Try with 'tahun' field if current format fails
            if (error.response?.status === 400) {
                try {
                    const alternativeData = { tahun: new Date().getFullYear() };

                    const retryResponse = await axios.post(
                        `/shu/user/${currentUser.id}/generate`,
                        alternativeData,
                    );

                    await invalidateAll();
                    closeModals();
                    showSuccessNotification("SHU pribadi berhasil digenerate!");
                    return;
                } catch (retryError: any) {
                    console.error(
                        "❌ Alternative format also failed:",
                        retryError,
                    );
                }
            }

            const errorMessage =
                error.response?.data?.message ||
                error.response?.data?.error ||
                error.message ||
                "API endpoint may not be implemented";

            showError(
                `Gagal generate SHU pribadi: ${errorMessage}\n\nEndpoint: /shu/user/${currentUser.id}/generate\nStatus: ${error.response?.status || "Unknown"}`,
            );
        }
    }

    async function saveUserSHU(tahun: number) {
        try {
            // Validation
            if (!tahun || tahun < 2020 || tahun > 2030) {
                showError(
                    "Tahun tidak valid. Silakan masukkan tahun antara 2020-2030",
                );
                return;
            }

            if (!currentUser?.id) {
                showError(
                    "Error: User ID tidak ditemukan. Silakan login ulang.",
                );
                return;
            }

            const saveRequest: SHUAnggotaSaveRequest = {
                tahun: tahun,
            };

            const response = await axios.post<SHUAnggotaSaveResponse>(
                `/shu-anggota/user/${currentUser.id}/save`,
                saveRequest,
            );

            // Refresh user history to show the newly saved record
            await invalidateAll();

            showSuccessNotification(
                `SHU untuk tahun ${tahun} berhasil disimpan!`,
            );

            return response.data.data;
        } catch (error: any) {
            console.error("❌ Error saving user SHU:", error);
            console.error("❌ Error response:", error.response?.data);
            console.error("❌ Error status:", error.response?.status);

            // Handle specific error cases
            if (error.response?.status === 403) {
                showError(
                    "Access Denied: Anda tidak memiliki izin untuk menyimpan SHU pribadi.\n\nKemungkinan penyebab:\n• Fitur belum aktif\n• Role/permission tidak sesuai",
                );
                return;
            }

            if (error.response?.status === 401) {
                showError(
                    "Authentication Error: Sesi login Anda mungkin telah berakhir.\n\nSilakan refresh halaman dan login kembali.",
                );
                return;
            }

            if (error.response?.status === 400) {
                const errorMessage =
                    error.response?.data?.message ||
                    error.response?.data?.error ||
                    "Data request tidak valid";
                showError(
                    `Gagal menyimpan SHU: ${errorMessage}\n\nPastikan:\n• Tahun yang dipilih valid\n• Anda memiliki data transaksi di tahun tersebut`,
                );
                return;
            }

            if (error.response?.status === 404) {
                showError(
                    `SHU untuk tahun ${tahun} tidak ditemukan.\n\nKemungkinan penyebab:\n• Data SHU tahun ${tahun} belum dibuat oleh admin\n• Tidak ada transaksi di tahun tersebut`,
                );
                return;
            }

            const errorMessage =
                error.response?.data?.message ||
                error.response?.data?.error ||
                error.message ||
                "Unknown error occurred";

            showError(
                `Gagal menyimpan SHU pribadi: ${errorMessage}\n\nEndpoint: /shu-anggota/user/${currentUser.id}/save\nStatus: ${error.response?.status || "Unknown"}`,
            );
        }
    }

