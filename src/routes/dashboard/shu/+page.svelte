    function openDetailModal(shu: SHURecord) {
        selectedSHU = shu;
        showDetailModal = true;

        // If shu_report is missing, try to fetch detailed data
        if (!shu.shu_report && canManageSHU) {
            fetchDetailedSHUData(shu);
        }
